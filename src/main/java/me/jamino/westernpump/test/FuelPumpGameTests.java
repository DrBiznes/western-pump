/**
 * Server-side behaviour tests. Run with {@code ./gradlew runGameTestServer}.
 *
 * <p>Templates are flat floors generated by {@code tools/make_test_template.py}; every block is
 * placed from code. {@code platform} is 5x3x3, {@code pump_yard} is 7x6x5 for setups that need a
 * tank under the pump and a motor-driven cogwheel beside it.
 */
@GameTestHolder(WesternPump.MOD_ID)
@PrefixGameTestTemplate(false)
public class FuelPumpGameTests {

    private static final String PLATFORM = "platform";
    private static final String YARD = "pump_yard";

    /** Placing the lower half must create the upper half, and both must survive. */
    @GameTest(template = PLATFORM)
    public static void placesTwoBlocksTall(GameTestHelper helper) {
        BlockPos pos = new BlockPos(1, 1, 1);
        placePump(helper, pos);

        helper.succeedWhen(() -> {
            BlockState lower = helper.getBlockState(pos);
            BlockState upper = helper.getBlockState(pos.above());
            helper.assertBlockPresent(ModBlocks.FUEL_PUMP.get(), pos);
            helper.assertBlockPresent(ModBlocks.FUEL_PUMP.get(), pos.above());
            if (lower.getValue(FuelPumpBlock.HALF) != DoubleBlockHalf.LOWER) {
                helper.fail("lower half has the wrong HALF value");
            }
            if (upper.getValue(FuelPumpBlock.HALF) != DoubleBlockHalf.UPPER) {
                helper.fail("upper half has the wrong HALF value");
            }
        });
    }

    /** Fuel goes in through the bottom and nowhere else. */
    @GameTest(template = PLATFORM)
    public static void exposesFluidCapabilityOnlyBelow(GameTestHelper helper) {
        BlockPos pos = new BlockPos(1, 1, 1);
        placePump(helper, pos);

        helper.succeedWhen(() -> {
            BlockPos lower = helper.absolutePos(pos);
            BlockPos upper = helper.absolutePos(pos.above());
            if (capability(helper, lower, Direction.DOWN) == null) {
                helper.fail("lower half exposes no fluid handler on its bottom");
            }
            if (capability(helper, lower, Direction.NORTH) != null) {
                helper.fail("lower half must not accept fluid through its side");
            }
            if (capability(helper, upper, Direction.DOWN) != null || capability(helper, upper, Direction.NORTH) != null) {
                helper.fail("upper half must not expose a fluid handler");
            }
        });
    }

    /** The buffer must accept fuel pushed in from below, and report it back. */
    @GameTest(template = PLATFORM)
    public static void bufferAcceptsFluid(GameTestHelper helper) {
        BlockPos pos = new BlockPos(1, 1, 1);
        placePump(helper, pos);

        IFluidHandler cap = capability(helper, helper.absolutePos(pos), Direction.DOWN);
        if (cap == null) {
            helper.fail("no fluid handler to fill");
            return;
        }
        int filled = cap.fill(new FluidStack(Fluids.WATER, 500), IFluidHandler.FluidAction.EXECUTE);
        if (filled <= 0) {
            helper.fail("buffer refused fluid from below");
            return;
        }

        helper.succeedWhen(() -> {
            FuelPumpBlockEntity pump = pump(helper, pos);
            if (pump.getBufferContents().getAmount() != filled) {
                helper.fail("buffer reported " + pump.getBufferContents().getAmount()
                        + " but accepted " + filled);
            }
        });
    }

    /**
     * An attached, powered pump moves fuel into a real Create tank next to it, using the pump's
     * own attach + tick logic rather than a re-implementation.
     */
    @GameTest(template = PLATFORM, timeoutTicks = 200)
    public static void transfersFuelToAttachedTarget(GameTestHelper helper) {
        BlockPos pumpPos = new BlockPos(1, 1, 1);
        BlockPos tankPos = new BlockPos(3, 1, 1);
        placePump(helper, pumpPos);
        powerPump(helper, pumpPos, 32);
        helper.setBlock(tankPos, AllBlocks.FLUID_TANK.getDefaultState());

        FuelPumpBlockEntity pump = pump(helper, pumpPos);
        IFluidHandler source = capability(helper, helper.absolutePos(pumpPos), Direction.DOWN);
        if (source == null) {
            helper.fail("pump exposes no handler");
            return;
        }
        source.fill(new FluidStack(Fluids.WATER, 1000), IFluidHandler.FluidAction.EXECUTE);

        // Attach the nozzle to the tank exactly as a player click would.
        FuelEndpoint endpoint = FuelEndpoint.of(helper.getLevel(), helper.absolutePos(tankPos), Direction.WEST);
        pump.attachTo(endpoint);

        helper.succeedWhen(() -> {
            IFluidHandler receiver = capability(helper, helper.absolutePos(tankPos), Direction.WEST);
            if (receiver == null) {
                helper.fail("target tank exposes no handler");
                return;
            }
            int inTank = receiver.getFluidInTank(0).getAmount();
            if (inTank <= 0) {
                helper.fail("pump moved no fuel into the attached tank");
                return;
            }
            // Conservation: nothing may be created or destroyed in transit.
            int total = pump.getBufferContents().getAmount() + inTank;
            if (total != 1000) {
                helper.fail("fuel was duplicated or voided: total " + total + ", expected 1000");
            }
        });
    }

    /** Without rotation the pump is inert: an attached tank stays empty and the status says why. */
    @GameTest(template = PLATFORM, timeoutTicks = 100)
    public static void doesNotDispenseWithoutPower(GameTestHelper helper) {
        BlockPos pumpPos = new BlockPos(1, 1, 1);
        BlockPos tankPos = new BlockPos(3, 1, 1);
        placePump(helper, pumpPos);
        helper.setBlock(tankPos, AllBlocks.FLUID_TANK.getDefaultState());

        FuelPumpBlockEntity pump = pump(helper, pumpPos);
        capability(helper, helper.absolutePos(pumpPos), Direction.DOWN)
                .fill(new FluidStack(Fluids.WATER, 1000), IFluidHandler.FluidAction.EXECUTE);
        pump.attachTo(FuelEndpoint.of(helper.getLevel(), helper.absolutePos(tankPos), Direction.WEST));

        helper.runAfterDelay(60, () -> {
            IFluidHandler receiver = capability(helper, helper.absolutePos(tankPos), Direction.WEST);
            if (receiver.getFluidInTank(0).getAmount() != 0) {
                helper.fail("an unpowered pump dispensed fuel");
                return;
            }
            if (pump.getStatus() != FuelPumpBlockEntity.Status.UNPOWERED) {
                helper.fail("expected UNPOWERED status, got " + pump.getStatus());
                return;
            }
            helper.succeed();
        });
    }

    /**
     * The pump is its own pump: a tank directly underneath is drained upward only once a cogwheel
     * beside the base starts turning.
     */
    @GameTest(template = YARD, timeoutTicks = 300)
    public static void pullsFromTankBelowOnlyWhenPowered(GameTestHelper helper) {
        BlockPos sourcePos = new BlockPos(2, 1, 2);
        BlockPos pumpPos = new BlockPos(2, 2, 2);
        helper.setBlock(sourcePos, AllBlocks.FLUID_TANK.getDefaultState());
        placePump(helper, pumpPos);
        capability(helper, helper.absolutePos(sourcePos), Direction.UP)
                .fill(new FluidStack(Fluids.WATER, 4000), IFluidHandler.FluidAction.EXECUTE);

        FuelPumpBlockEntity pump = pump(helper, pumpPos);
        helper.runAfterDelay(40, () -> {
            if (pump.getBufferContents().getAmount() != 0) {
                helper.fail("pump pulled fuel without rotational power");
                return;
            }
            powerPump(helper, pumpPos, 32);
        });
        helper.succeedWhen(() -> {
            if (pump.getBufferContents().getAmount() <= 0) {
                helper.fail("powered pump did not pull from the tank below");
            }
        });
    }

    /**
     * The whole chain, and the regression for "fills a few buckets then stops": a source tank
     * through a Create pipe into the pump's bottom, powered by a cogwheel, hose attached to a
     * target tank. Every drop of a source larger than the buffer must end up in the target.
     */
    @GameTest(template = YARD, timeoutTicks = 800)
    public static void fillsWholeTargetThroughPipeNetwork(GameTestHelper helper) {
        final int amount = 6000;
        BlockPos sourcePos = new BlockPos(1, 1, 2);
        BlockPos pipePos = new BlockPos(2, 1, 2);
        BlockPos pumpPos = new BlockPos(2, 2, 2);
        BlockPos targetPos = new BlockPos(2, 2, 0);

        helper.setBlock(sourcePos, AllBlocks.FLUID_TANK.getDefaultState());
        helper.setBlock(pipePos, AllBlocks.FLUID_PIPE.getDefaultState());
        placePump(helper, pumpPos);
        helper.setBlock(targetPos, AllBlocks.FLUID_TANK.getDefaultState());
        powerPump(helper, pumpPos, 256);

        capability(helper, helper.absolutePos(sourcePos), Direction.EAST)
                .fill(new FluidStack(Fluids.WATER, amount), IFluidHandler.FluidAction.EXECUTE);

        FuelPumpBlockEntity pump = pump(helper, pumpPos);
        pump.attachTo(FuelEndpoint.of(helper.getLevel(), helper.absolutePos(targetPos), Direction.SOUTH));

        helper.succeedWhen(() -> {
            int inTarget = capability(helper, helper.absolutePos(targetPos), Direction.SOUTH).getFluidInTank(0).getAmount();
            int inSource = capability(helper, helper.absolutePos(sourcePos), Direction.EAST).getFluidInTank(0).getAmount();
            int inBuffer = pump.getBufferContents().getAmount();
            if (inTarget < amount) {
                helper.fail("target has " + inTarget + "/" + amount + " (source " + inSource
                        + ", buffer " + inBuffer + ", status " + pump.getStatus() + ")");
                return;
            }
            if (inTarget + inSource + inBuffer != amount) {
                helper.fail("fuel was duplicated or voided: " + (inTarget + inSource + inBuffer) + " != " + amount);
            }
        });
    }

    // ---- helpers -------------------------------------------------------------------------

    private static void placePump(GameTestHelper helper, BlockPos pos) {
        helper.setBlock(pos, ModBlocks.FUEL_PUMP.getDefaultState());
        // setBlock does not run setPlacedBy, so place the upper half explicitly, mirroring it.
        helper.setBlock(pos.above(), ModBlocks.FUEL_PUMP.getDefaultState()
                .setValue(FuelPumpBlock.HALF, DoubleBlockHalf.UPPER));
    }

    /** A cogwheel east of the pump's base, driven from above by a creative motor at the given RPM. */
    private static void powerPump(GameTestHelper helper, BlockPos pumpPos, int rpm) {
        BlockPos cogPos = pumpPos.east();
        BlockPos motorPos = cogPos.above();
        helper.setBlock(cogPos, AllBlocks.COGWHEEL.getDefaultState());
        helper.setBlock(motorPos, AllBlocks.CREATIVE_MOTOR.getDefaultState()
                .setValue(CreativeMotorBlock.FACING, Direction.DOWN));
        BlockEntity motor = helper.getBlockEntity(motorPos);
        if (motor instanceof CreativeMotorBlockEntity creativeMotor) {
            creativeMotor.generatedSpeed.setValue(rpm);
        } else {
            helper.fail("creative motor missing at " + motorPos);
        }
    }

    private static FuelPumpBlockEntity pump(GameTestHelper helper, BlockPos pos) {
        return (FuelPumpBlockEntity) helper.getBlockEntity(pos);
    }

    private static IFluidHandler capability(GameTestHelper helper, BlockPos absolute, Direction side) {
        return helper.getLevel().getCapability(Capabilities.FluidHandler.BLOCK, absolute, side);
    }

    /**
     * Regression test for the crash on opening the creative inventory:
     * {@code IllegalArgumentException: Itemstack 1 westernpump:fuel_pump already exists in the
     * tab's list}. Builds every creative tab the way the inventory screen does and asserts our
     * item appears exactly once in total.
     */
    @GameTest(template = PLATFORM)
    public static void fuelPumpAppearsInExactlyOneCreativeTab(GameTestHelper helper) {
        var params = new net.minecraft.world.item.CreativeModeTab.ItemDisplayParameters(
                net.minecraft.world.flag.FeatureFlags.DEFAULT_FLAGS,
                true,
                helper.getLevel().registryAccess());

        int totalStacks = 0;
        java.util.List<String> tabsContaining = new java.util.ArrayList<>();

        for (var entry : net.minecraft.core.registries.BuiltInRegistries.CREATIVE_MODE_TAB.entrySet()) {
            net.minecraft.world.item.CreativeModeTab tab = entry.getValue();
            if (tab.getType() != net.minecraft.world.item.CreativeModeTab.Type.CATEGORY) {
                continue;
            }
            // buildContents throws outright if a duplicate stack was contributed.
            tab.buildContents(params);
            long here = tab.getDisplayItems().stream()
                    .filter(stack -> stack.getItem() == ModBlocks.FUEL_PUMP.asItem())
                    .count();
            if (here > 0) {
                tabsContaining.add(entry.getKey().location().toString());
                totalStacks += (int) here;
            }
        }

        if (totalStacks != 1) {
            helper.fail("fuel pump appears " + totalStacks + " time(s) in tabs " + tabsContaining
                    + "; expected exactly 1");
            return;
        }

        // With Diesel Generators installed it must live in that mod's tab, not our fallback.
        boolean diesel = net.neoforged.fml.ModList.get().isLoaded("createdieselgenerators");
        String expected = diesel
                ? "createdieselgenerators:cdg_creative_tab"
                : "westernpump:main";
        if (!tabsContaining.contains(expected)) {
            helper.fail("fuel pump should be in " + expected + " but was in " + tabsContaining);
            return;
        }
        helper.succeed();
    }

    /** Guards the endpoint's identity check, which is what stops a hose re-targeting a new block. */
    @GameTest(template = PLATFORM)
    public static void endpointRoundTripsThroughNbt(GameTestHelper helper) {
        FuelEndpoint endpoint = new FuelEndpoint(new BlockPos(4, 5, 6), Direction.EAST, null);
        FuelEndpoint loaded = FuelEndpoint.load(endpoint.save(helper.getLevel().registryAccess()));
        if (loaded == null || !loaded.equals(endpoint)) {
            helper.fail("endpoint did not survive a save/load round trip: " + loaded);
            return;
        }
        helper.succeed();
    }
}
